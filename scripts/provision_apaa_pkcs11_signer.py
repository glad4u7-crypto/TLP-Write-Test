#!/usr/bin/env python3
"""Explicit PKCS#11 Ed25519 keypair provisioning inside an existing token.

The private key is generated by the token; plaintext private material is never
exported. This script requires explicit --confirm-create, a hidden PIN prompt,
and refuses to reuse an existing object ID. It does not rotate or delete keys.
"""
from __future__ import annotations

import argparse
import getpass
import hashlib
import json
import os
from pathlib import Path
import re
import sys
from pathlib import Path

from cryptography.exceptions import InvalidSignature
from cryptography.hazmat.primitives.asymmetric.ed25519 import Ed25519PublicKey

from core.pkcs11_ed25519_signer import PKCS11Ed25519InspectorSigner, PKCS11SignerError

_ED25519_OID = bytes.fromhex("06032b6570")
_KEY_ID = re.compile(r"^[A-Za-z0-9_.:-]{1,64}$")


class PKCS11ProvisionError(RuntimeError):
    """PKCS#11 key provisioning failed closed."""


def provision_and_self_test(
    *, module_path: str, token_label: str, key_id: str, label: str,
    pin: str, pkcs11_api, signer_class=PKCS11Ed25519InspectorSigner,
) -> dict[str, object]:
    module = Path(module_path).expanduser()
    if not module.is_absolute() or not module.is_file() or module.is_symlink():
        raise PKCS11ProvisionError("PKCS#11 module path must be an absolute regular non-symlink file.")
    if type(key_id) is not str or not _KEY_ID.fullmatch(key_id):
        raise PKCS11ProvisionError("PKCS#11 key ID is invalid.")
    if type(token_label) is not str or not token_label or len(token_label) > 128:
        raise PKCS11ProvisionError("PKCS#11 token label is invalid.")
    if type(label) is not str or not label or len(label) > 128:
        raise PKCS11ProvisionError("PKCS#11 key label is invalid.")
    if type(pin) is not str or not 4 <= len(pin.encode("utf-8")) <= 128:
        raise PKCS11ProvisionError("PKCS#11 PIN length is invalid.")
    key_id_bytes = key_id.encode("ascii")
    try:
        library = pkcs11_api.lib(str(module))
        token = library.get_token(token_label=token_label)
        with token.open(rw=True, user_pin=pin.encode("utf-8")) as session:
            existing = list(session.get_objects({pkcs11_api.Attribute.ID: key_id_bytes}))
            if existing:
                raise PKCS11ProvisionError("Key ID already exists; refusing overwrite.")
            session.generate_keypair(
                pkcs11_api.KeyType.EC_EDWARDS,
                id=key_id_bytes,
                label=label,
                store=True,
                mechanism=pkcs11_api.Mechanism.EC_EDWARDS_KEY_PAIR_GEN,
                public_template={
                    pkcs11_api.Attribute.TOKEN: True,
                    pkcs11_api.Attribute.VERIFY: True,
                    pkcs11_api.Attribute.EC_PARAMS: _ED25519_OID,
                },
                private_template={
                    pkcs11_api.Attribute.TOKEN: True,
                    pkcs11_api.Attribute.PRIVATE: True,
                    pkcs11_api.Attribute.SENSITIVE: True,
                    pkcs11_api.Attribute.EXTRACTABLE: False,
                    pkcs11_api.Attribute.SIGN: True,
                },
            )
        signer = signer_class(
            module_path=str(module), token_label=token_label,
            key_id=key_id, user_pin=pin,
            pkcs11_loader=lambda _path: pkcs11_api,
        )
        public = signer.public_key_bytes()
        challenge = b"APAA-PKCS11-PROVISION-CHECK-V1:" + os.urandom(32)
        signature = signer.sign(challenge)
        Ed25519PublicKey.from_public_bytes(public).verify(signature, challenge)
        return {
            "status": "TOKEN_KEY_CREATED_AND_SELF_TEST_PASS",
            "algorithm": "Ed25519",
            "key_id": key_id,
            "public_key_sha256": hashlib.sha256(public).hexdigest(),
            "private_key_export": "NOT_REQUESTED",
            "token_hardware_identity": "NOT_INDEPENDENTLY_VERIFIED",
            "rotation_or_revocation": "NOT_PERFORMED",
            "backup_restore_qualification": "NOT_ASSESSED",
            "independent_review": "PENDING",
        }
    except PKCS11ProvisionError:
        raise
    except (PKCS11SignerError, InvalidSignature, ValueError, TypeError, OSError):
        raise PKCS11ProvisionError("PKCS#11 key provisioning or self-test failed closed.") from None
    except Exception:
        raise PKCS11ProvisionError("PKCS#11 token rejected key provisioning; no qualification claim made.") from None


def main(argv: list[str] | None = None, *, pkcs11_api_loader=None, pin_reader=None) -> int:
    parser = argparse.ArgumentParser(description="Provision one non-extractable APAA Ed25519 key inside a PKCS#11 token")
    parser.add_argument("--module", required=True)
    parser.add_argument("--token-label", required=True)
    parser.add_argument("--key-id", required=True)
    parser.add_argument("--label", default="APAA Inspector Signing Key")
    parser.add_argument("--confirm-create", action="store_true", help="Required explicit authorization to create a new token key")
    args = parser.parse_args(argv)
    if not args.confirm_create:
        print("Refusing to create a token key without --confirm-create.", file=sys.stderr)
        return 2
    pin_reader = pin_reader or getpass.getpass
    pin = pin_reader("PKCS#11 user PIN (input hidden): ")
    try:
        if pkcs11_api_loader is None:
            import pkcs11
            api = pkcs11
        else:
            api = pkcs11_api_loader()
        result = provision_and_self_test(
            module_path=args.module, token_label=args.token_label,
            key_id=args.key_id, label=args.label, pin=pin, pkcs11_api=api,
        )
        print(json.dumps({"schema_version": 1, **result}, sort_keys=True, indent=2))
        return 0
    except Exception:
        print("PKCS#11 provisioning failed closed; no private key was exported.", file=sys.stderr)
        return 2


if __name__ == "__main__":
    raise SystemExit(main())
